/** Removes duplicate sources (by url), keeping first-seen order. */
export function uniqueSources(list: readonly Source[]): Source[] {
  const seen = new Set<string>();
  return list.filter((s) => (seen.has(s.url) ? false : (seen.add(s.url), true)));
}
